    /**
     * Loads player history from database and populates tblPlayers using a non-editable DefaultTableModel.
     */
    public void loadPlayerData() {
        if (playerDAO == null) {
            playerDAO = new PlayerDAO();
        }

        String[] columnNames = {"ID", "Player Name", "Highest Round", "Prize Won", "Status", "Played At"};
        DefaultTableModel model = new DefaultTableModel(columnNames, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        try {
            List<PlayerResult> results = playerDAO.getAllPlayerResults();
            if (results != null) {
                for (PlayerResult p : results) {
                    model.addRow(new Object[]{
                        p.getId(),
                        p.getPlayerName(),
                        p.getHighestRound(),
                        p.getPrizeWon(),
                        p.getStatus(),
                        p.getPlayedAt()
                    });
                }
            }
        } catch (Exception ex) {
            logger.log(java.util.logging.Level.WARNING, "Error loading player data: " + ex.getMessage(), ex);
        }

        tblPlayers.setModel(model);
    }

