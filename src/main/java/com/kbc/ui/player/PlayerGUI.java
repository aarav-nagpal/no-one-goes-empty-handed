    private void btnFiftyFiftyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiftyFiftyActionPerformed
        if (gameEngine == null || !gameEngine.isLifelineAvailable(LifelineType.FIFTY_FIFTY)) {
            return;
        }
        try {
            @SuppressWarnings("unchecked")
            List<String> hidden = (List<String>) gameEngine.useLifeline(LifelineType.FIFTY_FIFTY);
            btnFiftyFifty.setEnabled(false);
            for (String opt : hidden) {
                if ("A".equalsIgnoreCase(opt)) {
                    btnOptA.setEnabled(false);
                    btnOptA.setVisible(false);
                } else if ("B".equalsIgnoreCase(opt)) {
                    btnOptB.setEnabled(false);
                    btnOptB.setVisible(false);
                } else if ("C".equalsIgnoreCase(opt)) {
                    btnOptC.setEnabled(false);
                    btnOptC.setVisible(false);
                } else if ("D".equalsIgnoreCase(opt)) {
                    btnOptD.setEnabled(false);
                    btnOptD.setVisible(false);
                }
            }
        } catch (Exception ex) {
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnFiftyFiftyActionPerformed

