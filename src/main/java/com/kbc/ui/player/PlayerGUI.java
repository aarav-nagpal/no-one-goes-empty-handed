    private void btnDoubleDipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDoubleDipActionPerformed
        if (gameEngine == null || !gameEngine.isLifelineAvailable(LifelineType.DOUBLE_DIP)) {
            return;
        }
        try {
            gameEngine.useLifeline(LifelineType.DOUBLE_DIP);
            btnDoubleDip.setEnabled(false);
            btnQuit.setEnabled(false);
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this,
                        "Double Dip is active! You have 2 attempts on this question. Quitting is disabled.",
                        "Double Dip Activated",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception ex) {
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDoubleDipActionPerformed

    private void btnFlipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFlipActionPerformed
        if (gameEngine == null || !gameEngine.isLifelineAvailable(LifelineType.FLIP)) {
            return;
        }
        try {
            gameEngine.useLifeline(LifelineType.FLIP);
            btnFlip.setEnabled(false);
            loadQuestionToUI();
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this,
                        "Question flipped! Here is your replacement question for Round " + gameEngine.getSession().getCurrentRound() + ".",
                        "Question Flipped",
                        JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (Exception ex) {
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnFlipActionPerformed

    private void btnQuitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitActionPerformed
        if (gameEngine == null || gameEngine.isGameOver()) {
            return;
        }
        if (!gameEngine.canQuit()) {
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this,
                        "Double Dip is active! You cannot quit on this question—you must guess!",
                        "Cannot Quit",
                        JOptionPane.WARNING_MESSAGE);
            }
            return;
        }

        int choice = JOptionPane.YES_OPTION;
        if (shouldShowDialog()) {
            choice = JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to quit and take home ₹" + gameEngine.getSession().getCurrentPrize() + "?",
                    "Quit Game",
                    JOptionPane.YES_NO_OPTION);
        }

        if (choice == JOptionPane.YES_OPTION) {
            gameEngine.quitGame();
            if (shouldShowDialog()) {
                JOptionPane.showMessageDialog(this,
                        "Game Over! You chose to walk away.\nPlayer: " + gameEngine.getSession().getPlayerName() +
                        "\nFinal Prize Won: ₹" + gameEngine.getSession().getCurrentPrize(),
                        "Quit Game",
                        JOptionPane.INFORMATION_MESSAGE);
            }
            lblBank.setText("Bank: ₹" + gameEngine.getSession().getCurrentPrize());
            disableAllButtons();
        }
    }//GEN-LAST:event_btnQuitActionPerformed

    private void handleAnswer(String option, JButton clickedBtn) {
        if (gameEngine == null || gameEngine.isGameOver()) {
            return;
        }

        Question currentQ = gameEngine.getCurrentQuestion();
        AnswerResult result = gameEngine.submitAnswer(option);

        switch (result) {
            case DOUBLE_DIP_FIRST_WRONG:
                if (shouldShowDialog()) {
                    JOptionPane.showMessageDialog(this,
                            "Incorrect! But Double Dip is active—you have ONE more attempt on this question.",
                            "Double Dip Active",
                            JOptionPane.WARNING_MESSAGE);
                }
                if (clickedBtn != null) {
                    clickedBtn.setEnabled(false);
                }
                break;

            case WRONG_GAME_OVER:
                String correctOpt = currentQ != null ? currentQ.getCorrectOpt() : "";
                if (shouldShowDialog()) {
                    JOptionPane.showMessageDialog(this,
                            "aaaagg🔥\nWrong answer! The correct answer was: " + correctOpt,
                            "Game Over",
                            JOptionPane.ERROR_MESSAGE);
                }
                lblBank.setText("Bank: ₹" + gameEngine.getSession().getCurrentPrize());
                disableAllButtons();
                break;

            case GAME_WON:
                if (shouldShowDialog()) {
                    JOptionPane.showMessageDialog(this,
                            "7 croree!! hame dedo",
                            "Winner!",
                            JOptionPane.INFORMATION_MESSAGE);
                }
                lblBank.setText("Bank: ₹" + gameEngine.getSession().getCurrentPrize());
                lblRound.setText("Round: 10/10");
                disableAllButtons();
                break;

            case CORRECT:
                loadQuestionToUI();
                break;
        }
    }

    private void loadQuestionToUI() {
        if (gameEngine == null) {
            return;
        }
        Question q = gameEngine.getCurrentQuestion();
        PlayerSession session = gameEngine.getSession();
        if (q == null || session == null) {
            return;
        }

        lblRound.setText("Round: " + session.getCurrentRound() + "/" + GameEngine.TOTAL_ROUNDS);
        lblBank.setText("Bank: ₹" + session.getCurrentPrize());
        txtQuestion.setText(q.getQuestionText());

        btnOptA.setText("<html><b>A:</b> " + q.getOptA() + "</html>");
        btnOptB.setText("<html><b>B:</b> " + q.getOptB() + "</html>");
        btnOptC.setText("<html><b>C:</b> " + q.getOptC() + "</html>");
        btnOptD.setText("<html><b>D:</b> " + q.getOptD() + "</html>");

        btnOptA.setEnabled(true);
        btnOptA.setVisible(true);
        btnOptB.setEnabled(true);
        btnOptB.setVisible(true);
        btnOptC.setEnabled(true);
        btnOptC.setVisible(true);
        btnOptD.setEnabled(true);
        btnOptD.setVisible(true);

        btnFiftyFifty.setEnabled(gameEngine.isLifelineAvailable(LifelineType.FIFTY_FIFTY));
        btnDoubleDip.setEnabled(gameEngine.isLifelineAvailable(LifelineType.DOUBLE_DIP));
        btnFlip.setEnabled(gameEngine.isLifelineAvailable(LifelineType.FLIP));
        btnQuit.setEnabled(gameEngine.canQuit());
    }

