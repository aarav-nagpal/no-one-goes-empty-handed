    private boolean shouldShowDialog() {
        return !java.awt.GraphicsEnvironment.isHeadless() && !Boolean.getBoolean("kbc.noninteractive");
    }

    private void initGame() {
        configureInitialButtons();
        String name = "Player 1";
        if (shouldShowDialog()) {
            String input = JOptionPane.showInputDialog(this, "Enter your name to play KBC:", "Player Name", JOptionPane.QUESTION_MESSAGE);
            if (input != null && !input.trim().isEmpty()) {
                name = input.trim();
            }
        }
        gameEngine = new GameEngine();
        gameEngine.startNewGame(name);
        setTitle("KBC - " + gameEngine.getSession().getPlayerName());
        loadQuestionToUI();
    }

